using System;
using System.IO;
using Xunit;
using SldFile;
using SldFile.Sketches;
using SldFile.Tests.Integration.Framework;
using SolidWorks.Interop.sldworks;

namespace SldFile.Tests.Integration.Tests;

[Collection("SolidWorksIntegration")]
public class SketchIntegrationTests
{
    private readonly SolidWorksApplicationFixture _fixture;

    public SketchIntegrationTests(SolidWorksApplicationFixture fixture)
    {
        _fixture = fixture;
    }

    private static string? LocateTestFile(string relativeOrName)
    {
        string[] candidates =
        {
            Path.Combine(AppContext.BaseDirectory, relativeOrName),
            Path.Combine(AppContext.BaseDirectory, "TestFiles", relativeOrName),
            Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", "SldFileTests", "TestFiles", relativeOrName),
            Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", "models", relativeOrName)
        };

        foreach (var c in candidates)
        {
            if (File.Exists(c)) return Path.GetFullPath(c);
        }
        return null;
    }

    [SolidWorksFact]
    public void NativeSketch_OpenedInSolidWorks_MatchesSldFileParsedFeature()
    {
        string? samplePath = LocateTestFile(Path.Combine("Sketches2026", "line10.SLDPRT"))
                           ?? LocateTestFile("cube.SLDPRT");

        if (samplePath == null) return;

        // 1. Parse via SldFile
        using var file = SwFile.Open(samplePath);
        var sketches = file.GetSketches();
        Assert.NotEmpty(sketches);
        var expectedSketch = sketches[0];

        // 2. Open via real SOLIDWORKS application
        IModelDoc2? swDoc = _fixture.OpenDocument(samplePath, readOnly: true);
        Assert.NotNull(swDoc);

        try
        {
            // 3. Find feature by traversing feature tree in SOLIDWORKS
            IFeature? swFeat = null;
            for (var f = (IFeature?)swDoc.FirstFeature(); f != null; f = (IFeature?)f.GetNextFeature())
            {
                if (f.Name == expectedSketch.Name || f.GetTypeName2() == "ProfileFeature")
                {
                    swFeat = f;
                    break;
                }
            }

            Assert.NotNull(swFeat);
            Assert.Equal(expectedSketch.Name, swFeat.Name);

            // 4. Get specific sketch interface
            var swSketch = swFeat.GetSpecificFeature2() as ISketch;
            if (swSketch != null)
            {
                var swPoints = swSketch.GetSketchPoints2() as object[];
                if (swPoints != null && expectedSketch.Points.Count > 0)
                {
                    Assert.True(swPoints.Length >= expectedSketch.Points.Count);
                }
            }
        }
        finally
        {
            _fixture.CloseDocument(samplePath);
        }
    }

    [Fact]
    public void ProgrammaticSketchAuthoring_BuildsCompleteValidGraph()
    {
        // Standalone authoring test (runs in any environment without CAD startup)
        var sketch = new SketchFeature("AuthoredSketch");

        var p1 = sketch.AddPoint(0, 0);
        var p2 = sketch.AddPoint(0.1, 0);
        var p3 = sketch.AddPoint(0.1, 0.05);

        var l1 = sketch.AddLine(p1, p2);
        var l2 = sketch.AddLine(p2, p3);
        var c1 = sketch.AddCircle(0.05, 0.025, 0.01);

        sketch.AddHorizontal(l1);
        sketch.AddVertical(l2);
        sketch.AddPerpendicular(l1, l2);
        sketch.AddDistanceDimension(p1, p2, "Length", 0.1);

        // 3 points explicitly added + 2 points (center + perimeter) generated by AddCircle = 5 points
        Assert.Equal(5, sketch.Points.Count);
        Assert.Equal(3, sketch.Segments.Count);
        Assert.Equal(4, sketch.Relations.Count); // 3 geometric + 1 dimension
        Assert.Single(sketch.Dimensions);

        var dim = sketch.Dimensions[0];
        Assert.Equal("Length", dim.Name);
        Assert.Equal(0.1, dim.SystemValue);
        Assert.Equal(2, dim.GetAttachedPoints().Count);
    }
}
