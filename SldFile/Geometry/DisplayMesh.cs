using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Numerics;
using System.Text;

namespace SldFile;

/// <summary>
/// Represents a decoded 3D display tessellation mesh extracted from SolidWorks DisplayLists.
/// Positions are in millimeters.
/// </summary>
public sealed class DisplayMesh
{
    public IReadOnlyList<Vector3> Positions { get; internal set; } = Array.Empty<Vector3>();
    public IReadOnlyList<Vector3> Normals { get; internal set; } = Array.Empty<Vector3>();
    public IReadOnlyList<int> TriangleIndices { get; internal set; } = Array.Empty<int>();
    public IReadOnlyList<(int Start, int End)> OutlineEdges { get; internal set; } = Array.Empty<(int, int)>();
    public IReadOnlyList<DisplayMeshPart> Parts { get; internal set; } = Array.Empty<DisplayMeshPart>();

    public Vector3 Min { get; internal set; } = new(float.PositiveInfinity, float.PositiveInfinity, float.PositiveInfinity);
    public Vector3 Max { get; internal set; } = new(float.NegativeInfinity, float.NegativeInfinity, float.NegativeInfinity);

    public int TriangleCount => TriangleIndices.Count / 3;
    public int VertexCount => Positions.Count;
    public int EdgeCount => OutlineEdges.Count;

    /// <summary>
    /// Writes this mesh to a Wavefront .OBJ stream/writer.
    /// </summary>
    public void WriteObj(TextWriter writer, float scale = 1.0f)
    {
        writer.WriteLine("# Generated by SldFile DisplayMesh");
        writer.WriteLine(string.Format(CultureInfo.InvariantCulture, "# Vertices: {0}, Triangles: {1}", Positions.Count, TriangleCount));

        for (int i = 0; i < Positions.Count; i++)
        {
            var p = Positions[i] * scale;
            writer.WriteLine(string.Format(CultureInfo.InvariantCulture, "v {0:F6} {1:F6} {2:F6}", p.X, p.Y, p.Z));
        }

        for (int i = 0; i < Normals.Count; i++)
        {
            var n = Normals[i];
            writer.WriteLine(string.Format(CultureInfo.InvariantCulture, "vn {0:F6} {1:F6} {2:F6}", n.X, n.Y, n.Z));
        }

        bool hasNormals = Normals.Count == Positions.Count;
        for (int i = 0; i < TriangleIndices.Count; i += 3)
        {
            int i0 = TriangleIndices[i] + 1;
            int i1 = TriangleIndices[i + 1] + 1;
            int i2 = TriangleIndices[i + 2] + 1;

            if (hasNormals)
            {
                writer.WriteLine(string.Format(CultureInfo.InvariantCulture, "f {0}//{0} {1}//{1} {2}//{2}", i0, i1, i2));
            }
            else
            {
                writer.WriteLine(string.Format(CultureInfo.InvariantCulture, "f {0} {1} {2}", i0, i1, i2));
            }
        }
    }

    /// <summary>
    /// Writes this mesh as binary STL to the specified stream.
    /// </summary>
    public void WriteStl(Stream stream, float scale = 1.0f)
    {
        using var writer = new BinaryWriter(stream, Encoding.ASCII, leaveOpen: true);
        byte[] header = new byte[80];
        Encoding.ASCII.GetBytes("SldFile Exported STL").CopyTo(header, 0);
        writer.Write(header);

        int triangleCount = TriangleCount;
        writer.Write((uint)triangleCount);

        for (int t = 0; t < TriangleIndices.Count; t += 3)
        {
            int i0 = TriangleIndices[t];
            int i1 = TriangleIndices[t + 1];
            int i2 = TriangleIndices[t + 2];

            Vector3 v0 = (i0 < Positions.Count ? Positions[i0] : Vector3.Zero) * scale;
            Vector3 v1 = (i1 < Positions.Count ? Positions[i1] : Vector3.Zero) * scale;
            Vector3 v2 = (i2 < Positions.Count ? Positions[i2] : Vector3.Zero) * scale;

            // Calculate face normal or use vertex normal
            Vector3 normal = Vector3.Zero;
            if (i0 < Normals.Count && i1 < Normals.Count && i2 < Normals.Count)
            {
                normal = Vector3.Normalize(Normals[i0] + Normals[i1] + Normals[i2]);
            }
            if (normal == Vector3.Zero)
            {
                normal = Vector3.Normalize(Vector3.Cross(v1 - v0, v2 - v0));
            }
            if (float.IsNaN(normal.X) || float.IsNaN(normal.Y) || float.IsNaN(normal.Z))
            {
                normal = Vector3.UnitZ;
            }

            writer.Write(normal.X);
            writer.Write(normal.Y);
            writer.Write(normal.Z);

            writer.Write(v0.X);
            writer.Write(v0.Y);
            writer.Write(v0.Z);

            writer.Write(v1.X);
            writer.Write(v1.Y);
            writer.Write(v1.Z);

            writer.Write(v2.X);
            writer.Write(v2.Y);
            writer.Write(v2.Z);

            writer.Write((ushort)0); // Attribute byte count
        }
    }

    /// <summary>
    /// Writes this mesh as a binary glTF 2.0 (.glb) container to the specified stream.
    /// Default scale is 0.001f (converting SolidWorks millimeters to glTF standard meters).
    /// </summary>
    public void WriteGlb(Stream stream, float scale = 0.001f)
    {
        Geometry.GlbWriter.Write(this, stream, scale);
    }
}

/// <summary>
/// A sub-part of the display mesh, typically corresponding to one face or surface in the model.
/// </summary>
public sealed class DisplayMeshPart
{
    public string Id { get; internal set; } = string.Empty;
    public int StreamIndex { get; internal set; }
    public int TableIndex { get; internal set; }
    public int TableOffset { get; internal set; }
    public int VertexStart { get; internal set; }
    public int VertexCount { get; internal set; }
    public int TriangleStart { get; internal set; }
    public int TriangleCount { get; internal set; }
    public int EdgeStart { get; internal set; }
    public int EdgeCount { get; internal set; }
    public int StripCount { get; internal set; }
    public bool NormalsDerived { get; internal set; }
    public uint? Color { get; internal set; }
    public string? ColorSource { get; internal set; }
    public string? AppearanceName { get; internal set; }
    public IReadOnlyList<DisplaySurfaceReference> SurfaceReferences { get; internal set; } = Array.Empty<DisplaySurfaceReference>();
}

/// <summary>
/// Persistent surface reference associated with a face mesh.
/// </summary>
public sealed class DisplaySurfaceReference
{
    public string Identity { get; set; } = string.Empty;
    public uint FeatureSourceId { get; set; }
    public uint LocalSurfaceId { get; set; }
}
